test_that("format_number", {
  expect_equal(format_number(c(1.342, 55.1284, NA, 0.1, 0, 1234.5678,
                               0.12345, 0.0012345, 0.00008788),
                             digits = 2, na = "N/A"),
               c("1.34", "55.13", "N/A", "0.10", "0", "1234.57",
                 "0.12", "0.0012", "0.000088"))

  expect_equal(format_number(-1 * c(1.342, 55.1284, NA, 0.1, 0, 1234.5678,
                               0.12345, 0.0012345),
                             digits = 2, na = "N/A"),
               c("-1.34", "-55.13", "N/A", "-0.10", "0", "-1234.57",
                 "-0.12", "-0.0012"))

  expect_equal(format_number(c(1.342, 55.1284, NA, 0.1, 0, 1234.5678,
                               0.12345, 0.0012345),
                             digits = 0, na = "N/A"),
               c("1", "55", "N/A", "0", "0", "1235",
                 "0", "0"))

  expect_equal(format_number(-1 * c(1.342, 55.1284, NA, 0.1, 0, 1234.5678,
                               0.12345, 0.0012345),
                             digits = 0, na = "N/A"),
               c("-1", "-55", "N/A", "0", "0", "-1235",
                 "0", "0"))
})
